    ' float halo=exp(-pow(dist/(.14+.06*max(yb-1.5,0.)),2.))*up*fall*.6;',
    ' col+=vec3(.2,.3,1.)*halo*(.7+haze*.6)+vec3(.65,.75,1.)*core*1.3;',
    ' // crystal',
    ' float t=0.;float hit=0.;vec3 p=ro;',
    ' for(int i=0;i<56;i++){p=ro+rd*t;float d=mapO(p);if(d<.0012){hit=1.;break;}t+=d;if(t>7.)break;}',
    ' if(hit>.5){vec3 n=normO(p);float c=cos(rotA),s=sin(rotA);vec3 nr=n;nr.xz=mat2(c,-s,s,c)*n.xz;float face=floor((atan(nr.z,nr.x)+3.14159)/1.0472);',
    '  float fh=fract(sin(face*12.9898)*43758.5453);vec3 v=-rd;float fr=pow(1.-max(dot(n,v),0.),3.);',
    '  vec3 base=vec3(.03,.05,.16)+vec3(.08,.14,.4)*fh;',
    '  float lit=.35+.65*max(dot(n,normalize(vec3(-.4,.7,.6))),0.);',
    '  vec3 em=mix(vec3(.15,.3,1.),vec3(1.),smoothstep(-.4,1.1,p.y))*(.28+.6*fh);',
    '  vec3 c2=base*lit+em*(.55+fr)+vec3(.55,.7,1.)*fr*1.5;',
    '  float edge=smoothstep(.55,.0,abs(dot(n,vec3(0.,1.,0.)))*.0+fract(atan(nr.z,nr.x)/1.0472+.5)*(1.-fract(atan(nr.z,nr.x)/1.0472+.5))*4.);',
    '  c2+=vec3(.6,.75,1.)*pow(1.-abs(2.*fract(atan(nr.z,nr.x)/1.0472+.5)-1.),14.)*.9;',
    '  col=c2;}',
    ' // dust along the beam',
    ' float dust=0.;for(int l=0;l<3;l++){float fl=float(l+1);float k=8.+fl*6.;vec2 g=vec2(q.x*k,q.y*k-fract(uA/6.2831)*float(3+l*2));vec2 id=floor(g);vec2 f=fract(g)-.5;float r=fract(sin(dot(id,vec2(12.9,78.2)))*43758.5);vec2 off=vec2(r-.5,fract(r*7.)-.5)*.5;float dd=length(f-off);dust+=smoothstep(.07,.0,dd)*step(.55,r)*exp(-q.x*q.x*6.)*(.4+.2*fl);}',
    ' col+=vec3(.6,.7,1.)*dust*.8;',
    ' col*=smoothstep(1.7,.4,length(vec2(q.x*.7,q.y)));return col;}',
    'vec3 fall(vec2 uv,float asp){',
    ' float ph=fract(uA/6.2831853);vec2 p=vec2(uv.x*asp,uv.y);float bx=.66*asp;float dx=p.x-bx;float y=uv.y;',
    ' vec2 lp=vec2(cos(uA),sin(uA))*uS;',
    ' float s=fbm(p*vec2(1.3,1.05)+lp);float sm=smoothstep(.28,.9,s);',
    ' vec3 col=vec3(.010,.014,.032);',
    ' float near=exp(-pow(dx/.62,2.));',
    ' col+=vec3(.08,.12,.42)*sm*(.25+near)*smoothstep(-.1,.85,y+.12);',
    ' col+=vec3(.26,.18,.62)*sm*exp(-pow((dx-.36)/.4,2.))*.4*smoothstep(.15,.9,y);',
