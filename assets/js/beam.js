    ' // floor',
    ' float tf=(-1.08-ro.y)/rd.y;',
    ' if(rd.y<0.&&tf>0.){vec3 fp=ro+rd*tf;float r=length(fp.xz);float ph=fract(uA/6.2831);float ring=exp(-pow((r-ph*3.)/.05,2.))*(1.-ph);col+=vec3(.25,.4,1.)*ring*.9;col+=vec3(.2,.3,1.)*exp(-r*1.9)*.85;col+=vec3(.55,.5,1.)*exp(-r*5.)*.7;float g=smoothstep(.02,0.,abs(fract(fp.x*1.5)-.5)-.47)+smoothstep(.02,0.,abs(fract(fp.z*1.5)-.5)-.47);col+=vec3(.1,.16,.4)*g*exp(-r*.9)*.35;}',
