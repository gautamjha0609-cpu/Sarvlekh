    ' vec2 p=vec2(uv.x*asp,uv.y);vec2 lp=vec2(cos(uA),sin(uA))*uS;',
    ' float bx=.66*asp;float dx=p.x-bx;',
    ' float s=fbm(p*2.2+lp)*.9+fbm(p*4.+lp*1.7)*.35;',
    ' float inv=1.-uv.y;float w=mix(.012,.17,pow(inv,1.7));float pulse=1.+.07*sin(uA);',
    ' float core=exp(-pow(dx/(w*.34),2.))*pulse;float halo=exp(-pow(dx/(w*2.6+.05),2.))*.75*pulse;',
    ' float gb=smoothstep(.62,0.,uv.y);',
    ' vec3 col=vec3(.018,.024,.045);',
    ' col+=vec3(.16,.26,1.)*halo*(.5+.7*s)*(.45+gb);',
    ' col+=vec3(.58,.36,1.)*exp(-pow((dx+.2)/.24,2.))*s*.28*gb;',
    ' col+=vec3(1.)*core*(.8+.2*s)*(.3+.7*smoothstep(1.,.05,uv.y));',
    ' col+=vec3(.1,.13,.34)*pow(s,3.)*.9*smoothstep(0.,1.,uv.y*.9+.1)*exp(-pow((dx-.38)/.62,2.));',
    ' col*=smoothstep(1.5,.35,length((uv-.5)*vec2(asp*.8,1.)));return col;}',
    'vec3 orb(vec2 uv,float asp){',
    ' vec2 c=(uv-.5)*vec2(asp,1.);float r=length(c);float ang=atan(c.y,c.x);',
    ' float n2=fbm(vec2(cos(ang+uA),sin(ang+uA))*1.5+r*3.);',
    ' float ring=exp(-pow((r-.3)/.075,2.));',
    ' float t=.5+.5*sin(ang+uA+n2*2.4);float o=smoothstep(.5,.95,.5+.5*sin(ang*2.-uA+n2*3.));vec3 pal=mix(mix(vec3(.18,.32,1.),vec3(.62,.4,1.),t),vec3(1.,.55,.22),o*.9);pal=mix(pal,vec3(1.),pow(ring,6.)*.35);',
