    ' float halo=exp(-pow(dx/(w*3.+.03),2.));float lift=.35+1.5*pow(low,1.8);',
    ' col+=bc*halo*lift*.5;',
    ' float core=exp(-pow(dx/(w*.55+.002),2.));col+=cc*core*lift*.45;',
    ' float fil=0.;',
    ' for(int k=0;k<11;k++){float fk=float(k);float o=(fk-5.)/5.*.92;float sp=3.2+fract(fk*.618)*2.4;float m=floor(1.+mod(fk,3.));float pp=fk*.37;',
