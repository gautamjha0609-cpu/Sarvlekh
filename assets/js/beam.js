    'vec3 obelisk(vec2 uv,float asp){',
    ' rotA=uA/6.;',
    ' vec2 q=(uv-.5)*vec2(asp,1.)*2.;q.x-=(.79-.5)*asp*2.;',
    ' vec3 ro=vec3(0.,.3,4.5);vec3 rd=normalize(vec3(q.x*.95,q.y*.95-.1,-1.7));',
    ' vec2 lp=vec2(cos(uA),sin(uA))*uS;',
    ' float haze=fbm(vec2(q.x*1.3,q.y*1.1)+lp*3.)*.9;',
