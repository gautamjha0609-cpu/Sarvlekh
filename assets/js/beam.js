    ' col+=vec3(1.,.55,.25)*exp(-pow((r-.2)/.11,2.))*.4*n2;col+=vec3(.2,.3,1.)*exp(-pow((r-.44)/.2,2.))*.3*(.5+n2);',
    ' col*=smoothstep(.78,.22,r);return col;}',
    'float sdHex(vec3 p,vec2 h){const vec3 k=vec3(-.8660254,.5,.57735);p=abs(p);p.xy-=2.*min(dot(k.xy,p.xy),0.)*k.xy;vec2 d=vec2(length(p.xy-vec2(clamp(p.x,-k.z*h.x,k.z*h.x),h.x))*sign(p.y-h.x),p.z-h.y);return min(max(d.x,d.y),0.)+length(max(d,0.));}',
    'float rotA;',
    'float mapO(vec3 p){float c=cos(rotA),s=sin(rotA);p.xz=mat2(c,-s,s,c)*p.xz;vec3 q=vec3(p.x,p.z,p.y-.21);float d=sdHex(q,vec2(.19,1.29));float cone=(p.y+length(p.xz)*3.6-1.5)*.16;return max(d,cone);}',
